/* Maps of vigilo.city: instances (home page, cities) and observations of an instance */
import { addBaseLayers } from './layers';
import { findPicture, openViewer } from './panoramax';

const STATUS = ['Nouvelle', 'Résolue', 'Prise en compte', 'En cours de résolution', 'Indiquée comme résolue'];

function escapeHtml(value) {
	return String(value === undefined || value === null ? '' : value)
		.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function readJson(id) {
	const el = document.getElementById(id);
	return el ? JSON.parse(el.textContent) : null;
}

function createMap(el, options) {
	const map = L.map(el, Object.assign({ scrollWheelZoom: false, zoomSnap: 0.5 }, options || {}));
	el.leafletMap = map;
	addBaseLayers(map);
	// zoom with the wheel only once the map has been clicked (no scroll trap)
	map.once('focus', () => map.scrollWheelZoom.enable());
	return map;
}

/* ---- Panoramax: click anywhere on the map to see the street */

function showPanoramaxAround(map, latlng, radius) {
	const popup = L.popup({ closeButton: false, className: 'pnx-popup' })
		.setLatLng(latlng)
		.setContent('<span class="spinner"></span> Recherche d\'une vue Panoramax…')
		.openOn(map);
	findPicture(latlng.lat, latlng.lng, radius).then((picture) => {
		if (picture) {
			map.closePopup(popup);
			openViewer(picture);
		} else {
			popup.setContent('Aucune vue Panoramax à proximité');
			setTimeout(() => map.closePopup(popup), 2500);
		}
	});
}

function enablePanoramax(map) {
	map.on('click', (e) => {
		// ~15 px around the click, at least ~30 m
		const p = map.latLngToContainerPoint(e.latlng);
		const corner = map.containerPointToLatLng(p.add([15, 15]));
		const radius = Math.max(0.0003, Math.abs(corner.lat - e.latlng.lat), Math.abs(corner.lng - e.latlng.lng));
		showPanoramaxAround(map, e.latlng, radius);
	});
	const Hint = L.Control.extend({
		onAdd() {
			const div = L.DomUtil.create('div', 'map-hint');
			div.innerHTML = '<span aria-hidden="true">📷</span> <span class="hint-long">Cliquez sur la carte pour voir la rue avec Panoramax</span><span class="hint-short">Vue de rue : cliquez sur la carte</span>';
			return div;
		}
	});
	new Hint({ position: 'bottomleft' }).addTo(map);
}

/* ---- All the instances */

function instancesMap(el) {
	const instances = readJson('instances-data') || [];
	const map = createMap(el, { center: [46.6, 2.4], zoom: 5.5 });
	const bounds = [];
	instances.filter((i) => i.center).forEach((i) => {
		const marker = L.circleMarker(i.center, {
			radius: 9, weight: 3, color: i.online ? '#1f2328' : '#9aa4b2', fillColor: i.online ? '#fdd835' : '#e3e6ea', fillOpacity: 1
		}).addTo(map);
		marker.bindTooltip(escapeHtml(i.display_name), { direction: 'top', offset: [0, -8], className: 'obs-tooltip' });
		let area = null;
		if (i.bbox) {
			area = L.rectangle([[i.bbox[0], i.bbox[1]], [i.bbox[2], i.bbox[3]]], {
				color: '#f2c200', weight: 2, fillOpacity: 0.08, interactive: false
			});
		}
		marker.on('mouseover', () => area && area.addTo(map));
		marker.on('mouseout', () => area && map.removeLayer(area));
		marker.bindPopup('<strong>' + escapeHtml(i.display_name) + '</strong>'
			+ (i.cities && i.cities.length ? '<br><span class="muted">' + i.cities.length + ' commune' + (i.cities.length > 1 ? 's' : '') + '</span>' : '')
			+ (i.url ? '<br><a href="' + escapeHtml(i.url) + '">Voir les observations</a> · <a href="https://app.vigilo.city/?instance=' + encodeURIComponent(i.name) + '">Ouvrir l\'appli</a>' : ''));
		bounds.push(i.center);
	});
	if (bounds.length && el.dataset.fit !== 'false') {
		map.fitBounds(bounds, { padding: [30, 30], maxZoom: 9 });
	}
}

/* ---- Observations of one instance */

// One distinct color per category (vigilo-conf colors are kept for unknown categories)
const CATEGORY_COLORS = {
	2: '#e5484d',   // Véhicule ou objet gênant
	3: '#8e4ec6',   // Aménagement mal conçu
	4: '#f76b15',   // Défaut d'entretien
	5: '#0090ff',   // Absence d'arceaux de stationnement
	6: '#e2a300',   // Signalisation, marquage
	7: '#d6409f',   // Incivilité récurrente sur la route
	8: '#12a594',   // Absence d'aménagement
	9: '#1f2328',   // Accident, chute, incident
	10: '#3e63dd',  // Vol ou dégradation de vélo
	11: '#a07553',  // Éclairage public insuffisant
	50: '#46a758', 51: '#ab4aba', 52: '#29a383', // COVID (anciennes catégories)
	100: '#8b8d98'  // Autre
};

function categoryColor(cat) {
	return CATEGORY_COLORS[cat.catid] || cat.catcolor || '#8b8d98';
}

// point size follows the zoom level
function radiusFor(zoom) {
	return zoom >= 17 ? 10 : zoom >= 15 ? 8 : zoom >= 13 ? 6 : 4.5;
}

function photoUrl(api, o) {
	// original photo of approved observations, panel generated by the backend otherwise
	return o.approved == 1 ? api + '/get_photo.php?token=' + encodeURIComponent(o.token)
		: api + '/generate_panel.php?s=300&token=' + encodeURIComponent(o.token);
}

function observationPopup(api, instance, cats, o) {
	const cat = cats[o.categorie] || {};
	const date = new Date(parseInt(o.time, 10) * 1000).toLocaleDateString('fr-FR');
	const panel = api + '/generate_panel.php?s=300&token=' + encodeURIComponent(o.token);
	return '<div class="obs-popup">'
		+ '<img src="' + escapeHtml(photoUrl(api, o)) + '" alt="" loading="lazy" onerror="if(this.src!==\'' + escapeHtml(panel) + '\')this.src=\'' + escapeHtml(panel) + '\'">'
		+ '<p class="obs-cat" style="--cat:' + escapeHtml(categoryColor(cat)) + '"><span class="dot"></span>' + escapeHtml(cat.catname || 'Autre') + '</p>'
		+ (o.comment ? '<p><strong>' + escapeHtml(o.comment) + '</strong></p>' : '')
		+ '<p class="muted">' + escapeHtml(o.address) + '<br>' + date + (STATUS[o.status] ? ' · ' + STATUS[o.status] : '') + '</p>'
		+ '<p class="obs-actions"><a href="https://app.vigilo.city/?token=' + encodeURIComponent(o.token) + '&instance=' + encodeURIComponent(instance) + '">Voir dans l\'appli</a>'
		+ '<button type="button" class="link-btn pnx-btn" data-lat="' + escapeHtml(o.coordinates_lat) + '" data-lon="' + escapeHtml(o.coordinates_lon) + '">Voir avec Panoramax</button></p>'
		+ '</div>';
}

/* Legend: resolution state and one line per category present, click to show / hide them */
function legendItems(kind, entries) {
	return entries.map((e) => '<li><label style="--cat:' + escapeHtml(e.color) + '">'
		+ '<input type="checkbox"' + (e.checked === false ? '' : ' checked') + ' data-kind="' + kind + '" data-id="' + escapeHtml(e.id) + '">'
		+ '<span class="dot' + (e.ring ? ' dot-ring' : '') + '"></span><span class="legend-name">' + escapeHtml(e.name) + '</span>'
		+ '<span class="legend-count">' + e.count + '</span></label></li>').join('');
}

function addLegend(map, states, entries, onToggle) {
	const Legend = L.Control.extend({
		onAdd() {
			const div = L.DomUtil.create('div', 'map-legend');
			div.innerHTML = '<button type="button" class="legend-toggle" aria-expanded="true">Filtres</button>'
				+ '<div class="legend-body"><p class="legend-title">État</p><ul>' + legendItems('state', states) + '</ul>'
				+ '<p class="legend-title">Catégories</p><ul>' + legendItems('cat', entries) + '</ul></div>';
			L.DomEvent.disableClickPropagation(div);
			L.DomEvent.disableScrollPropagation(div);
			div.addEventListener('change', (ev) => onToggle(ev.target.dataset.kind, ev.target.dataset.id, ev.target.checked));
			const toggle = div.querySelector('.legend-toggle');
			toggle.addEventListener('click', () => {
				const open = div.classList.toggle('collapsed') === false;
				toggle.setAttribute('aria-expanded', open);
			});
			// small screens: start folded
			if (map.getSize().x < 600) {
				div.classList.add('collapsed');
				toggle.setAttribute('aria-expanded', false);
			}
			return div;
		}
	});
	new Legend({ position: 'topright' }).addTo(map);
}

// status 1: resolved (the other ones: new, taken into account, in progress, reported as resolved)
function isResolved(o) {
	return parseInt(o.status, 10) === 1;
}

// One item per observation: before backend 0.0.27, an observation linked to several resolutions came once
// per resolution. Keep its most advanced status (resolved > reported resolved > in progress > taken into account).
const STATUS_RANK = { 1: 4, 4: 3, 3: 2, 2: 1, 0: 0 };
function uniqueIssues(issues) {
	const best = new Map();
	issues.forEach((o) => {
		const seen = best.get(o.token);
		if (!seen || (STATUS_RANK[parseInt(o.status, 10)] || 0) > (STATUS_RANK[parseInt(seen.status, 10)] || 0)) best.set(o.token, o);
	});
	return issues.filter((o) => best.get(o.token) === o);
}

async function observationsMap(el) {
	const api = el.dataset.api;
	const scope = el.dataset.scope;
	const instance = el.dataset.instance;
	const cats = {};
	(readJson('categories-data') || []).forEach((c) => { cats[c.catid] = c; });
	// canvas: thousands of points stay fluid
	const map = createMap(el, { center: [46.6, 2.4], zoom: 6, preferCanvas: true });
	const bbox = el.dataset.bbox ? JSON.parse(el.dataset.bbox) : null;
	if (bbox) {
		map.fitBounds([[bbox[0], bbox[1]], [bbox[2], bbox[3]]]);
	}
	enablePanoramax(map);

	map.on('popupopen', (e) => {
		const btn = e.popup.getElement().querySelector('.pnx-btn');
		if (btn) {
			btn.addEventListener('click', () => {
				btn.disabled = true;
				btn.textContent = 'Recherche…';
				findPicture(parseFloat(btn.dataset.lat), parseFloat(btn.dataset.lon), 0.0005).then((picture) => {
					if (picture) {
						openViewer(picture);
						btn.textContent = 'Voir avec Panoramax';
						btn.disabled = false;
					} else {
						btn.textContent = 'Pas de vue Panoramax ici';
					}
				});
			});
		}
	});

	// categories of the instance (backend >= 0.0.23: its own ones too), national list otherwise
	try {
		const rc = await fetch(api + '/get_categories.php');
		const list = rc.ok ? await rc.json() : null;
		if (Array.isArray(list)) list.forEach((c) => { cats[c.catid] = c; });
	} catch (e) { /* older instance: national list */ }

	const status = document.getElementById('observations-status');
	let issues;
	try {
		const r = await fetch(api + '/get_issues.php?scope=' + encodeURIComponent(scope) + '&count=3000');
		issues = await r.json();
		if (!Array.isArray(issues)) throw new Error('bad answer');
		issues = uniqueIssues(issues);
	} catch (e) {
		if (status) status.textContent = 'Les observations de cette instance ne peuvent pas être chargées pour le moment.';
		return;
	}

	const group = L.layerGroup().addTo(map);
	const counts = {};
	const stateCounts = { open: 0, resolved: 0 };
	const markers = [];
	const points = [];
	// oldest first, so the most recent observations are drawn on top
	issues.slice().reverse().forEach((o) => {
		const lat = parseFloat(o.coordinates_lat);
		const lon = parseFloat(o.coordinates_lon);
		if (isNaN(lat) || isNaN(lon)) return;
		const id = String(o.categorie);
		const cat = cats[o.categorie] || { catid: o.categorie };
		const state = isResolved(o) ? 'resolved' : 'open';
		// resolved: lighter, with a ring of the category color
		const style = state === 'resolved'
			? { weight: 2, color: categoryColor(cat), opacity: 0.9, fillColor: '#fff', fillOpacity: 0.85 }
			: { weight: 1.5, color: '#fff', opacity: 1, fillColor: categoryColor(cat), fillOpacity: 0.92 };
		const marker = L.circleMarker([lat, lon], Object.assign({ radius: radiusFor(map.getZoom()) }, style));
		marker.bindPopup(() => observationPopup(api, instance, cats, o), { maxWidth: 280, minWidth: 240 });
		marker.bindTooltip(escapeHtml(o.comment || cat.catname || 'Observation'), { direction: 'top', offset: [0, -6], className: 'obs-tooltip' });
		marker.on('mouseover', () => marker.setStyle({ weight: 3 }));
		marker.on('mouseout', () => marker.setStyle({ weight: style.weight }));
		marker.vigilo = { cat: id, state: state };
		group.addLayer(marker);
		counts[id] = (counts[id] || 0) + 1;
		stateCounts[state]++;
		markers.push(marker);
		points.push([lat, lon]);
	});
	map.on('zoomend', () => {
		const r = radiusFor(map.getZoom());
		markers.forEach((m) => m.setRadius(r));
	});
	// frame the observations (the territory's box is often much wider)
	if (points.length) {
		map.fitBounds(points, { padding: [24, 24], maxZoom: 15 });
	}
	const hidden = { cat: {}, state: {} };
	function showStatus() {
		if (!status) return;
		if (!issues.length) {
			status.textContent = 'Aucune observation pour le moment.';
			return;
		}
		const shown = markers.filter((m) => group.hasLayer(m)).length;
		status.textContent = shown + ' observation' + (shown > 1 ? 's' : '') + ' affichée' + (shown > 1 ? 's' : '')
			+ (shown < markers.length ? ' sur ' + markers.length : '');
	}
	showStatus();
	const entries = Object.keys(counts).map((id) => {
		const cat = cats[id] || { catid: id };
		return { id: id, name: cat.catname || 'Autre', color: categoryColor(cat), count: counts[id] };
	}).sort((a, b) => b.count - a.count);
	if (entries.length) {
		const states = [
			{ id: 'open', name: 'À résoudre', color: '#1f2328', count: stateCounts.open },
			{ id: 'resolved', name: 'Résolues', color: '#1f2328', count: stateCounts.resolved, ring: true }
		];
		addLegend(map, states, entries, (kind, id, visible) => {
			hidden[kind][id] = !visible;
			markers.forEach((m) => {
				const show = !hidden.cat[m.vigilo.cat] && !hidden.state[m.vigilo.state];
				if (show && !group.hasLayer(m)) group.addLayer(m);
				if (!show && group.hasLayer(m)) group.removeLayer(m);
			});
			showStatus();
		});
	}

	// latest observations
	const list = document.getElementById('latest-observations');
	if (list) {
		list.innerHTML = issues.slice(0, 10).map((o) => {
			const cat = cats[o.categorie] || { catid: o.categorie };
			return '<li><a href="https://app.vigilo.city/?token=' + encodeURIComponent(o.token) + '&instance=' + encodeURIComponent(instance) + '">'
				+ '<img src="' + escapeHtml(api + '/generate_panel.php?s=150&token=' + encodeURIComponent(o.token)) + '" alt="" loading="lazy">'
				+ '<span><strong>' + escapeHtml(o.comment || cat.catname || 'Observation') + '</strong>'
				+ '<span class="obs-cat small" style="--cat:' + escapeHtml(categoryColor(cat)) + '"><span class="dot"></span>' + escapeHtml(cat.catname || 'Autre') + '</span>'
				+ '<span class="muted">' + escapeHtml(o.address) + ' · ' + new Date(parseInt(o.time, 10) * 1000).toLocaleDateString('fr-FR') + '</span></span></a></li>';
		}).join('');
	}
}

/* ---- Contact e-mails are assembled on click (no address in the HTML for spam bots) */
function enableMailLinks() {
	document.querySelectorAll('a[data-mail-user]').forEach((a) => {
		a.addEventListener('click', () => {
			a.href = 'mailto:' + a.dataset.mailUser + '@' + a.dataset.mailDomain;
		});
	});
}

/* ---- Statistics of the web app embedded in the page: the iframe takes the height of its
   content, sent by the app (postMessage "vigilo-stats-height") */
function enableStatsFrames() {
	const frames = Array.from(document.querySelectorAll('iframe[data-stats-frame]'));
	if (!frames.length) return;
	window.addEventListener('message', (e) => {
		if (!e.data || e.data.type !== 'vigilo-stats-height') return;
		const height = parseInt(e.data.height, 10);
		frames.forEach((frame) => {
			if (frame.contentWindow === e.source && e.origin === new URL(frame.src).origin && height > 0 && height < 20000) {
				frame.style.height = height + 'px';
			}
		});
	});
}

document.querySelectorAll('[data-map="instances"]').forEach(instancesMap);
document.querySelectorAll('[data-map="observations"]').forEach(observationsMap);
enableMailLinks();
enableStatsFrames();
